import wave
import struct

# 1. Create a minimal 1x1 Red PNG Image (69 bytes)
tiny_png = bytes([
    0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,
    0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
    0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
    0x08, 0x02, 0x00, 0x00, 0x00, 0x90, 0x77, 0x53,
    0xDE, 0x00, 0x00, 0x00, 0x0C, 0x49, 0x44, 0x41,
    0x54, 0x08, 0xD7, 0x63, 0xF8, 0xCF, 0xC0, 0x00,
    0x00, 0x03, 0x01, 0x01, 0x00, 0x18, 0xDD, 0x8D,
    0xB0, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E,
    0x44, 0xAE, 0x42, 0x60, 0x82
])

with open("test_image.png", "wb") as f:
    f.write(tiny_png)

# 2. Create a minimal 0.1s WAV Audio File (~1.6 KB)
wav = wave.open("test_audio.wav", "w")
wav.setnchannels(1)     # Mono
wav.setsampwidth(2)    # 16-bit
wav.setframerate(8000) # 8kHz

# 800 silent frames (0.1 second)
frames = bytearray()
for _ in range(800):
    frames.extend(struct.pack('<h', 0))

wav.writeframes(frames)
wav.close()

print("Tiny test files generated successfully!")